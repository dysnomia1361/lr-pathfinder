import streamlit as st
import pandas as pd
import numpy as np
import joblib
import os

# Page config
st.set_page_config(
    page_title="Predicción de ACV",
    layout="centered",
)

st.title(" Prototipo de modelo Predicción de Accidente Cerebrovascular")
st.markdown(
    "Modelo de **Regresión Logística** entrenado con validación cruzada estratificada. "
    "Introduce los datos clínicos para obtener una estimación de riesgo."
)

# Loading model
@st.cache_resource
def load_model():
    base = os.path.dirname(__file__)
    path = os.path.join(base, "models", "lr_final.joblib")
    return joblib.load(path)

model = load_model()

# Input Format
with st.form("patient_form"):
    col1, col2 = st.columns(2)

    with col1:
        gender = st.selectbox("Género", ["Male", "Female"])
        age = st.number_input("Edad", min_value=0.0, max_value=120.0, value=60.0, step=1.0)
        hypertension = st.selectbox("Hipertensión", [0, 1], format_func=lambda x: "Sí" if x else "No")
        heart_disease = st.selectbox("Enfermedad cardíaca", [0, 1], format_func=lambda x: "Sí" if x else "No")
        ever_married = st.selectbox("¿Alguna vez casado/a?", ["Yes", "No"])

    with col2:
        work_type = st.selectbox(
            "Tipo de trabajo",
            ["Private", "Self-employed", "Govt_job", "children", "Never_worked"],
        )
        residence_type = st.selectbox("Residencia", ["Urban", "Rural"])
        avg_glucose = st.number_input(
            "Glucosa media (mg/dL)", min_value=40.0, max_value=400.0, value=100.0, step=1.0
        )
        bmi = st.number_input(
            "IMC (kg/m²)", min_value=10.0, max_value=70.0, value=28.0, step=0.1
        )
        smoking_status = st.selectbox(
            "Estado de tabaquismo",
            ["never smoked", "formerly smoked", "smokes", "unknown"],
        )

    submitted = st.form_submit_button("Calcular riesgo")

# Prediction
if submitted:
    
    input_df = pd.DataFrame(
        [{
            "gender": gender,
            "age": age,
            "hypertension": hypertension,
            "heart_disease": heart_disease,
            "ever_married": ever_married,
            "work_type": work_type,
            "Residence_type": residence_type,
            "avg_glucose_level": avg_glucose,
            "bmi": bmi,
            "smoking_status": smoking_status,
        }]
    )

    proba = model.predict_proba(input_df)[0, 1]
    # Threshold for the LR model
    threshold = 0.53
    pred = int(proba >= threshold)

    st.divider()
    if pred == 1:
        st.error(f"Riesgo elevado detectado (probabilidad: {proba:.1%})")
    else:
        st.success(f"Riesgo no elevado (probabilidad: {proba:.1%})")

    st.caption(
        f"Umbral de decisión: {threshold:.2f} (optimizado para Recall/F2). "
        "Este resultado es orientativo y no sustituye el criterio médico."
    )

    # Show input data as a table
    with st.expander("Ver datos introducidos"):
        st.dataframe(input_df.T.rename(columns={0: "Valor"}))
